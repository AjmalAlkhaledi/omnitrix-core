/**
 * A database row as an object, with relationships.
 *
 * ```php
 * final class User extends Model
 * {
 *     protected static array $fillable = ['name', 'email'];
 *     protected static array $hidden = ['password'];
 *     protected static array $casts = ['is_admin' => 'bool', 'settings' => 'array'];
 *
 *     public function posts(): HasMany
 *     {
 *         return $this->hasMany(Post::class);
 *     }
 * }
 *
 * $user = User::create(['name' => 'Ann', 'email' => 'ann@example.com']);
 * $users = User::with('posts')->where('is_admin', true)->get();
 * ```
 *
 * The table defaults to the plural snake case of the class name (`BlogPost` → `blog_posts`) and
 * the primary key to `id`. Models are plain objects created per request; they hold no
 * connection and are safe to use from any coroutine. Returning a model, a {@see Collection} or a
 * {@see Paginator} from a route handler produces JSON.
 *
 * @implements ArrayAccess<string, mixed>
 */
abstract class Model implements ArrayAccess, JsonSerializable
{
    /** Table name; derived from the class name when null. */
    protected static ?string $table = null;

    protected static string $primaryKey = 'id';

    /** Whether the primary key is generated by the database (AUTO_INCREMENT). */
    protected static bool $incrementing = true;

    /** Connection name from the `database` configuration; null uses the default. */
    protected static ?string $connection = null;

    /** Maintain `created_at` and `updated_at`. */
    protected static bool $timestamps = true;

    /** @var list<string> attributes accepted by create(), fill() and update() */
    protected static array $fillable = [];

    /** @var list<string> attributes left out of toArray() and JSON */
    protected static array $hidden = [];

    /** @var array<string, string> attribute => int|float|bool|string|array|json|datetime|date */
    protected static array $casts = [];

    /** @var array<class-string, array<string, bool>> */
    private static array $relationMethods = [];

    /** @var array<string, mixed> raw column values */
    private array $attributes = [];

    /** @var array<string, mixed> values as last read from or written to the database */
    private array $original = [];

    /** @var array<string, Model|Collection<covariant Model>|null> */
    private array $relations = [];

    private bool $exists = false;

    /** @param array<string, mixed> $attributes fillable attributes */
    final public function __construct(array $attributes = [])
    {
        $this->fill($attributes);
    }

    // --- static entry points ---------------------------------------------------------------

    /** @return ModelQuery<static> */
    public static function query(): ModelQuery
    {
        return new ModelQuery(static::class, static::connection()->table(static::table()));
    }

    /** @return Collection<static> */
    public static function all(): Collection
    {
        return static::query()->get();
    }

    /** @return static|null */
    public static function find(int|string $id): ?static
    {
        return static::query()->find($id);
    }

    /** @return static */
    public static function findOrFail(int|string $id): static
    {
        return static::query()->findOrFail($id);
    }

    /**
     * @param array<string, mixed> $attributes
     *
     * @return static
     */
    public static function create(array $attributes): static
    {
        $model = new static($attributes);
        $model->save();

        return $model;
    }

    /**
     * @param string|array<int|string, string|callable(ModelQuery<covariant Model>): mixed> ...$relations
     *
     * @return ModelQuery<static>
     */
    public static function with(string|array ...$relations): ModelQuery
    {
        return static::query()->with(...$relations);
    }

    /**
     * @param string|Expression|(Closure(Builder): void)|array<string, mixed> $column
     *
     * @return ModelQuery<static>
     */
    public static function where(string|Expression|Closure|array $column, mixed $operator = null, mixed $value = null): ModelQuery
    {
        $query = static::query();

        return match (func_num_args()) {
            1 => $query->where($column),
            2 => $query->where($column, $operator),
            default => $query->where($column, $operator, $value),
        };
    }

    public static function table(): string
    {
        return static::$table ?? Str::plural(Str::snake(self::baseName(static::class)));
    }

    public static function keyName(): string
    {
        return static::$primaryKey;
    }

    /** Foreign key other tables use to reference this model: `User` → `user_id`. */
    public static function foreignKeyName(): string
    {
        return Str::snake(self::baseName(static::class)) . '_' . static::$primaryKey;
    }

    public static function connection(): Database
    {
        return DB::connection(static::$connection);
    }

    public static function usesTimestamps(): bool
    {
        return static::$timestamps;
    }

    /**
     * Creates a model for a row read from the database.
     *
     * @internal
     *
     * @param array<string, mixed> $row
     */
    public static function fromRow(array $row): static
    {
        $model = new static();
        $model->attributes = $row;
        $model->original = $row;
        $model->exists = true;

        return $model;
    }

    // --- attributes -------------------------------------------------------------------------

    /**
     * Sets fillable attributes; keys not listed in `$fillable` are ignored.
     *
     * @param array<string, mixed> $attributes
     */
    public function fill(array $attributes): static
    {
        foreach ($attributes as $key => $value) {
            if (in_array($key, static::$fillable, true)) {
                $this->setAttribute($key, $value);
            }
        }

        return $this;
    }

    /**
     * Sets attributes without the `$fillable` check. Use only with trusted input.
     *
     * @param array<string, mixed> $attributes
     */
    public function forceFill(array $attributes): static
    {
        foreach ($attributes as $key => $value) {
            $this->setAttribute($key, $value);
        }

        return $this;
    }

    public function getAttribute(string $key): mixed
    {
        if (array_key_exists($key, $this->attributes)) {
            return $this->castGet($key, $this->attributes[$key]);
        }
        if (array_key_exists($key, $this->relations)) {
            return $this->relations[$key];
        }
        if (self::isRelationMethod(static::class, $key)) {
            $method = [$this, $key];
            $relation = is_callable($method) ? $method() : null;
            $result = $relation instanceof Relation ? $relation->getResults() : null;
            $this->relations[$key] = $result;

            return $result;
        }

        return null;
    }

    public function setAttribute(string $key, mixed $value): void
    {
        $this->attributes[$key] = $this->castSet($key, $value);
    }

    public function getKey(): int|string|null
    {
        $key = $this->attributes[static::$primaryKey] ?? null;

        return is_int($key) || is_string($key) ? $key : (is_numeric($key) ? (int) $key : null);
    }

    public function exists(): bool
    {
        return $this->exists;
    }

    /** @return array<string, mixed> raw attribute values */
    public function getAttributes(): array
    {
        return $this->attributes;
    }

    /** @return array<string, mixed> attributes changed since the model was read or saved */
    public function getDirty(): array
    {
        $dirty = [];
        foreach ($this->attributes as $key => $value) {
            if (!array_key_exists($key, $this->original) || $this->original[$key] !== $value) {
                $dirty[$key] = $value;
            }
        }

        return $dirty;
    }

    public function isDirty(?string $attribute = null): bool
    {
        $dirty = $this->getDirty();

        return $attribute === null ? $dirty !== [] : array_key_exists($attribute, $dirty);
    }

    // --- events -----------------------------------------------------------------------------

    /** Events whose listeners can cancel the operation by returning false. */
    private const array HALTING = ['saving', 'creating', 'updating', 'deleting'];

    private const array EVENTS = ['saving', 'saved', 'creating', 'created', 'updating', 'updated', 'deleting', 'deleted'];

    /** @var array<class-string, array<string, list<callable(static): mixed>>> listeners per model class */
    private static array $modelListeners = [];

    /**
     * Registers a listener for one model event of this class: saving, saved, creating, created,
     * updating, updated, deleting, deleted. A `saving`, `creating`, `updating` or `deleting`
     * listener that returns false cancels the operation (save()/delete() return false). The
     * events are also dispatched as `model.{event}: {class}` to the event dispatcher.
     *
     * @param callable(static): mixed $listener
     */
    public static function on(string $event, callable $listener): void
    {
        if (!in_array($event, self::EVENTS, true)) {
            throw new InvalidArgumentException("Unknown model event '{$event}'");
        }
        self::$modelListeners[static::class][$event][] = $listener;
    }

    /** @param callable(static): mixed $listener */
    public static function creating(callable $listener): void
    {
        static::on('creating', $listener);
    }

    /** @param callable(static): mixed $listener */
    public static function created(callable $listener): void
    {
        static::on('created', $listener);
    }

    /** @param callable(static): mixed $listener */
    public static function updating(callable $listener): void
    {
        static::on('updating', $listener);
    }

    /** @param callable(static): mixed $listener */
    public static function updated(callable $listener): void
    {
        static::on('updated', $listener);
    }

    /** @param callable(static): mixed $listener */
    public static function saving(callable $listener): void
    {
        static::on('saving', $listener);
    }

    /** @param callable(static): mixed $listener */
    public static function saved(callable $listener): void
    {
        static::on('saved', $listener);
    }

    /** @param callable(static): mixed $listener */
    public static function deleting(callable $listener): void
    {
        static::on('deleting', $listener);
    }

    /** @param callable(static): mixed $listener */
    public static function deleted(callable $listener): void
    {
        static::on('deleted', $listener);
    }

    /**
     * Registers an observer: an object (or class) whose public methods named after model events
     * (`created(User $user)`, `deleting(User $user)`, …) become listeners.
     */
    public static function observe(object|string $observer): void
    {
        $instance = is_string($observer) ? new $observer() : $observer;
        foreach (self::EVENTS as $event) {
            $callable = [$instance, $event];
            if (is_callable($callable)) {
                static::on($event, $callable);
            }
        }
    }

    /** Removes the listeners of this model class (tests). */
    public static function flushEventListeners(): void
    {
        unset(self::$modelListeners[static::class]);
    }

    /** Runs the listeners of `$event`; false when a halting event was cancelled. */
    protected function fireModelEvent(string $event): bool
    {
        $halting = in_array($event, self::HALTING, true);
        foreach (self::$modelListeners[static::class][$event] ?? [] as $listener) {
            if ($listener($this) === false && $halting) {
                return false;
            }
        }
        $container = Facade::container();
        if ($container !== null && $container->has(EventDispatcher::class)) {
            $dispatcher = $container->get(EventDispatcher::class);
            if ($dispatcher instanceof EventDispatcher) {
                $name = "model.{$event}: " . static::class;
                if ($halting) {
                    return $dispatcher->until($name, [$this]) !== false;
                }
                $dispatcher->dispatch($name, [$this]);
            }
        }

        return true;
    }

    // --- persistence ------------------------------------------------------------------------

    /** Inserts the model, or updates the changed attributes of an existing one. */
    public function save(): bool
    {
        if (!$this->fireModelEvent('saving')) {
            return false;
        }
        $now = (new DateTimeImmutable())->format('Y-m-d H:i:s');
        if ($this->exists) {
            $dirty = $this->getDirty();
            if ($dirty === []) {
                return true;
            }
            if (!$this->fireModelEvent('updating')) {
                return false;
            }
            $dirty = $this->getDirty(); // listeners may have changed attributes
            if (static::$timestamps && !array_key_exists('updated_at', $dirty)) {
                $this->attributes['updated_at'] = $now;
                $dirty['updated_at'] = $now;
            }
            static::connection()->table(static::table())->where(static::$primaryKey, $this->getKey())->update($dirty);
            $this->original = $this->attributes;
            $this->fireModelEvent('updated');
        } else {
            if (!$this->fireModelEvent('creating')) {
                return false;
            }
            if (static::$timestamps) {
                $this->attributes['created_at'] ??= $now;
                $this->attributes['updated_at'] ??= $now;
            }
            $builder = static::connection()->table(static::table());
            if (static::$incrementing && !isset($this->attributes[static::$primaryKey])) {
                $this->attributes[static::$primaryKey] = $builder->insertGetId($this->attributes);
            } else {
                $builder->insert($this->attributes);
            }
            $this->exists = true;
            $this->original = $this->attributes;
            $this->fireModelEvent('created');
        }
        $this->original = $this->attributes;
        $this->fireModelEvent('saved');

        return true;
    }

    /**
     * Fills and saves in one step.
     *
     * @param array<string, mixed> $attributes fillable attributes
     */
    public function update(array $attributes): bool
    {
        return $this->fill($attributes)->save();
    }

    public function delete(): bool
    {
        if (!$this->exists) {
            return false;
        }
        if (!$this->fireModelEvent('deleting')) {
            return false;
        }
        static::connection()->table(static::table())->where(static::$primaryKey, $this->getKey())->delete();
        $this->exists = false;
        $this->fireModelEvent('deleted');

        return true;
    }

    /** Reloads the attributes from the database and forgets loaded relations. */
    public function refresh(): static
    {
        $row = static::connection()->table(static::table())->where(static::$primaryKey, $this->getKey())->first();
        if ($row === null) {
            throw new ModelNotFoundException(static::class, [$this->getKey()]);
        }
        $this->attributes = $row;
        $this->original = $row;
        $this->relations = [];

        return $this;
    }

    // --- relations --------------------------------------------------------------------------

    /**
     * Eager loads relations on this model (see {@see ModelQuery::with()}).
     *
     * @param string|array<int|string, string|callable(ModelQuery<covariant Model>): mixed> ...$relations
     */
    public function load(string|array ...$relations): static
    {
        (new Collection([$this]))->load(...$relations);

        return $this;
    }

    /** @param Model|Collection<covariant Model>|null $value */
    public function setRelation(string $name, Model|Collection|null $value): void
    {
        $this->relations[$name] = $value;
    }

    public function relationLoaded(string $name): bool
    {
        return array_key_exists($name, $this->relations);
    }

    /** @return Model|Collection<covariant Model>|null */
    public function getRelation(string $name): Model|Collection|null
    {
        return $this->relations[$name] ?? null;
    }

    /**
     * One related row whose foreign key points at this model: `users.id` ← `profiles.user_id`.
     *
     * @template TRelated of Model
     *
     * @param class-string<TRelated> $related
     *
     * @return HasOne<TRelated>
     */
    protected function hasOne(string $related, ?string $foreignKey = null, ?string $localKey = null): HasOne
    {
        return new HasOne($this, $related, $foreignKey ?? static::foreignKeyName(), $localKey ?? static::$primaryKey);
    }

    /**
     * Many related rows whose foreign key points at this model: `users.id` ← `posts.user_id`.
     *
     * @template TRelated of Model
     *
     * @param class-string<TRelated> $related
     *
     * @return HasMany<TRelated>
     */
    protected function hasMany(string $related, ?string $foreignKey = null, ?string $localKey = null): HasMany
    {
        return new HasMany($this, $related, $foreignKey ?? static::foreignKeyName(), $localKey ?? static::$primaryKey);
    }

    /**
     * The row this model's foreign key points at: `posts.user_id` → `users.id`.
     *
     * @template TRelated of Model
     *
     * @param class-string<TRelated> $related
     *
     * @return BelongsTo<TRelated>
     */
    protected function belongsTo(string $related, ?string $foreignKey = null, ?string $ownerKey = null): BelongsTo
    {
        return new BelongsTo($this, $related, $foreignKey ?? $related::foreignKeyName(), $ownerKey ?? $related::keyName());
    }

    /**
     * Many-to-many through a pivot table. The pivot table defaults to both singular table names
     * in alphabetical order (`posts` + `tags` → `post_tag`).
     *
     * @template TRelated of Model
     *
     * @param class-string<TRelated> $related
     *
     * @return BelongsToMany<TRelated>
     */
    protected function belongsToMany(string $related, ?string $pivotTable = null, ?string $foreignPivotKey = null, ?string $relatedPivotKey = null): BelongsToMany
    {
        if ($pivotTable === null) {
            $names = [Str::singular(static::table()), Str::singular($related::table())];
            sort($names);
            $pivotTable = implode('_', $names);
        }

        return new BelongsToMany($this, $related, $pivotTable, $foreignPivotKey ?? static::foreignKeyName(), $relatedPivotKey ?? $related::foreignKeyName(), static::$primaryKey, $related::keyName());
    }

    // --- serialisation ----------------------------------------------------------------------

    /** @return array<string, mixed> cast attributes and loaded relations, without hidden attributes */
    public function toArray(): array
    {
        $array = [];
        foreach (array_keys(array_diff_key($this->attributes, array_flip(static::$hidden))) as $key) {
            $value = $this->castGet($key, $this->attributes[$key]);
            $array[$key] = $value instanceof DateTimeInterface ? $value->format(DateTimeInterface::ATOM) : $value;
        }
        foreach ($this->relations as $name => $related) {
            if (!in_array($name, static::$hidden, true)) {
                $array[$name] = $related?->toArray();
            }
        }

        return $array;
    }

    /** @return array<string, mixed> */
    public function jsonSerialize(): array
    {
        return $this->toArray();
    }

    // --- magic access -----------------------------------------------------------------------

    public function __get(string $name): mixed
    {
        return $this->getAttribute($name);
    }

    public function __set(string $name, mixed $value): void
    {
        $this->setAttribute($name, $value);
    }

    public function __isset(string $name): bool
    {
        return $this->getAttribute($name) !== null;
    }

    public function __unset(string $name): void
    {
        unset($this->attributes[$name], $this->relations[$name]);
    }

    public function offsetExists(mixed $offset): bool
    {
        return is_string($offset) && $this->__isset($offset);
    }

    public function offsetGet(mixed $offset): mixed
    {
        return is_string($offset) ? $this->getAttribute($offset) : null;
    }

    public function offsetSet(mixed $offset, mixed $value): void
    {
        if (!is_string($offset)) {
            throw new LogicException('Model attributes need string names');
        }
        $this->setAttribute($offset, $value);
    }

    public function offsetUnset(mixed $offset): void
    {
        if (is_string($offset)) {
            $this->__unset($offset);
        }
    }

    // --- casting ----------------------------------------------------------------------------

    private function castType(string $key): ?string
    {
        $type = static::$casts[$key] ?? null;
        if ($type === null && static::$timestamps && ($key === 'created_at' || $key === 'updated_at')) {
            return 'datetime';
        }

        return $type;
    }

    private function castGet(string $key, mixed $value): mixed
    {
        $type = $this->castType($key);
        if ($type === null || $value === null) {
            return $value;
        }

        return match ($type) {
            'int', 'integer' => is_numeric($value) ? (int) $value : $value,
            'float', 'double', 'decimal' => is_numeric($value) ? (float) $value : $value,
            'bool', 'boolean' => is_bool($value) ? $value : in_array($value, [1, '1', 'true'], true),
            'string' => is_scalar($value) ? (string) $value : $value,
            'array', 'json' => is_string($value) ? self::decodeJson($value) : $value,
            'datetime', 'date' => $value instanceof DateTimeInterface ? $value : (is_string($value) ? new DateTimeImmutable($value) : $value),
            default => $value,
        };
    }

    private function castSet(string $key, mixed $value): mixed
    {
        $type = $this->castType($key);
        if ($value === null) {
            return null;
        }
        if ($value instanceof DateTimeInterface) {
            return $value->format($type === 'date' ? 'Y-m-d' : 'Y-m-d H:i:s');
        }
        if (($type === 'array' || $type === 'json') && !is_string($value)) {
            return json_encode($value, JSON_THROW_ON_ERROR);
        }
        if (is_bool($value)) {
            return $value ? 1 : 0;
        }
        if (is_array($value)) {
            throw new LogicException("Attribute '{$key}' of " . static::class . " holds an array; add it to \$casts as 'array'");
        }

        return $value;
    }

    private static function decodeJson(string $value): mixed
    {
        try {
            return json_decode($value, true, 512, JSON_THROW_ON_ERROR);
        } catch (JsonException) {
            return $value;
        }
    }

    /** @param class-string $class */
    private static function isRelationMethod(string $class, string $method): bool
    {
        if (isset(self::$relationMethods[$class][$method])) {
            return self::$relationMethods[$class][$method];
        }
        $is = false;
        if (method_exists($class, $method)) {
            $reflection = new ReflectionMethod($class, $method);
            $type = $reflection->getReturnType();
            $is = $reflection->isPublic() && !$reflection->isStatic() && $reflection->getNumberOfRequiredParameters() === 0
                && $reflection->getDeclaringClass()->getName() !== self::class
                && $type instanceof ReflectionNamedType && is_a($type->getName(), Relation::class, true);
        }
        self::$relationMethods[$class][$method] = $is;

        return $is;
    }

    private static function baseName(string $class): string
    {
        $base = strrchr($class, '\\');

        return $base === false ? $class : substr($base, 1);
    }

    /** @internal removes a helper column added by a relation query (not a change to save) */
    public function forgetAttribute(string $key): void
    {
        unset($this->attributes[$key], $this->original[$key]);
    }
}
