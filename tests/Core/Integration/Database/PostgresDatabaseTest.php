/**
 * The database layer against a real PostgreSQL (skipped when none is running, required in CI):
 * builder SQL, generated keys, limited writes, transactions, error classification, timeouts,
 * concurrency and the row/query cache with cascades and PL/pgSQL triggers.
 */
#[CoversClass(PgSqlDriver::class)]
#[CoversClass(PgSqlGrammar::class)]
#[CoversClass(CacheSchema::class)]
final class PostgresDatabaseTest extends TestCase
{
    private const string DB = 'omnitrix_pg_test';

    private PDO $behind;

    /** @var list<DatabaseManager> */
    private array $managers = [];

    /** @var list<RedisClient> */
    private array $clients = [];

    protected function setUp(): void
    {
        parent::setUp();
        $this->behind = Services::pgDatabase(self::DB);
        $this->behind->exec('CREATE TABLE users (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(50) NOT NULL, email VARCHAR(100) NOT NULL UNIQUE, active BOOLEAN NOT NULL DEFAULT TRUE, score INTEGER NOT NULL DEFAULT 0)');
        $this->behind->exec('CREATE TABLE posts (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE, title VARCHAR(50) NOT NULL, status VARCHAR(10) NOT NULL DEFAULT \'draft\')');
        $this->behind->exec('CREATE TABLE counters (id INTEGER PRIMARY KEY, n INTEGER NOT NULL)');
        $this->behind->exec('INSERT INTO counters VALUES (1, 0)');
        $this->behind->exec('CREATE TABLE audit (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, note TEXT NOT NULL)');
        $this->behind->exec(<<<'SQL'
            CREATE FUNCTION count_audit() RETURNS trigger LANGUAGE plpgsql AS $$
            BEGIN
              UPDATE counters SET n = n + 1 WHERE id = 1;
              RETURN NEW;
            END $$
            SQL);
        $this->behind->exec('CREATE TRIGGER audit_count AFTER INSERT ON audit FOR EACH ROW EXECUTE FUNCTION count_audit()');
    }

    protected function tearDown(): void
    {
        foreach ($this->managers as $manager) {
            $manager->close();
        }
        foreach ($this->clients as $client) {
            $client->close();
        }
        parent::tearDown();
    }

    public function testBuilderKeysTypesAndLimitedWrites(): void
    {
        $db = $this->database();
        $ann = $db->table('users')->insertGetId(['name' => 'Ann', 'email' => 'ann@example.com']);
        $bob = $db->table('users')->insertGetId(['name' => 'Bob', 'email' => 'bob@example.com', 'active' => false]);
        self::assertSame([1, 2], [$ann, $bob], 'identity keys come back through RETURNING');
        self::assertSame(3, $db->table('users')->insert([['name' => 'Cy', 'email' => 'cy@example.com', 'score' => 5], ['name' => 'Dee', 'email' => 'dee@example.com', 'score' => 7], ['name' => 'Eve', 'email' => 'eve@example.com', 'score' => 9]]));

        $row = $db->table('users')->find($bob);
        self::assertSame(['id' => 2, 'name' => 'Bob', 'email' => 'bob@example.com', 'active' => false, 'score' => 0], $row, 'integers and booleans keep their types');
        self::assertSame(['Cy', 'Dee'], array_column($db->table('users')->where('score', '>', 0)->orderBy('id')->limit(2)->get(), 'name'));
        self::assertSame(['Dee', 'Eve'], array_column($db->table('users')->whereIn('id', [4, 5])->orderBy('id')->get(), 'name'));
        self::assertSame(4, $db->table('users')->where('active', true)->count());
        self::assertSame(21, (int) $db->table('users')->sum('score'));

        self::assertSame(2, $db->table('users')->where('score', '>', 0)->orderBy('score', 'desc')->limit(2)->update(['score' => 0]));
        self::assertSame([5, 0, 0], array_column($db->table('users')->whereIn('id', [3, 4, 5])->orderBy('id')->get(), 'score'), 'only the two highest scores were updated');
        self::assertSame(1, $db->table('users')->where('active', true)->orderBy('id', 'desc')->limit(1)->delete());
        self::assertNull($db->table('users')->find(5));
        self::assertSame(1, $db->table('users')->where('id', 1)->increment('score', 3));
        self::assertSame(3, $db->table('users')->find(1)['score'] ?? null);
    }

    public function testTransactionsSavepointsAndErrors(): void
    {
        $db = $this->database();
        $db->transaction(function () use ($db): void {
            $db->table('users')->insert(['name' => 'Ann', 'email' => 'ann@example.com']);
            try {
                $db->transaction(function () use ($db): void {
                    $db->table('users')->insert(['name' => 'Bob', 'email' => 'bob@example.com']);
                    throw new RuntimeException('inner fails');
                });
            } catch (RuntimeException) {
                // the savepoint is rolled back; the outer transaction continues
            }
        });
        self::assertSame(['Ann'], array_column($db->table('users')->get(), 'name'));

        try {
            $db->table('users')->insert(['name' => 'Ann 2', 'email' => 'ann@example.com']);
            self::fail('duplicate email must fail');
        } catch (UniqueConstraintViolationException $e) {
            self::assertSame('23505', $e->sqlState());
        }
        try {
            $db->table('posts')->insert(['user_id' => 999, 'title' => 'x']);
            self::fail('missing parent must fail');
        } catch (ConstraintViolationException $e) {
            self::assertSame('23503', $e->sqlState());
        }

        $slow = $this->database(['statement_timeout' => 0.3]);
        $t = hrtime(true);
        try {
            $slow->select('select pg_sleep(2)');
            self::fail('statement_timeout must interrupt the query');
        } catch (QueryTimeoutException $e) {
            self::assertSame('57014', $e->sqlState());
        }
        self::assertLessThan(1.5, (hrtime(true) - $t) / 1e9);
        self::assertSame([['ok' => 1]], $slow->select('select 1 as ok'), 'the connection is usable after a timeout');
    }

    public function testDeadlocksAreClassifiedAndQueriesRunConcurrently(): void
    {
        $db = $this->database();
        $db->table('users')->insert([['name' => 'A', 'email' => 'a@x'], ['name' => 'B', 'email' => 'b@x']]);
        $done = new Channel(2);
        foreach ([[1, 2], [2, 1]] as $order) {
            \OpenSwoole\Coroutine::create(function () use ($db, $order, $done): void {
                try {
                    $db->transaction(function () use ($db, $order): void {
                        $db->table('users')->where('id', $order[0])->update(['score' => 1]);
                        $db->select('select pg_sleep(0.3)');
                        $db->table('users')->where('id', $order[1])->update(['score' => 2]);
                    });
                    $done->push('ok');
                } catch (DeadlockException) {
                    $done->push('deadlock');
                } catch (Throwable $e) {
                    $done->push($e::class . ': ' . $e->getMessage());
                }
            });
        }
        $results = [$done->pop(10.0), $done->pop(10.0)];
        sort($results);
        self::assertSame(['deadlock', 'ok'], $results, 'PostgreSQL detects the deadlock (40P01) and one transaction wins; got ' . json_encode($results));

        $t = hrtime(true);
        $wait = new Channel(4);
        for ($i = 0; $i < 4; $i++) {
            \OpenSwoole\Coroutine::create(static function () use ($db, $wait): void {
                $db->select('select pg_sleep(0.3)');
                $wait->push(true);
            });
        }
        for ($i = 0; $i < 4; $i++) {
            $wait->pop(5.0);
        }
        self::assertLessThan(0.9, (hrtime(true) - $t) / 1e9, 'four 300 ms queries overlap on pooled connections');
    }

    public function testRowAndQueryCacheWithCascadesAndPlpgsqlTriggers(): void
    {
        $this->behind->exec("INSERT INTO users (name, email) VALUES ('Ann', 'ann@example.com'), ('Bob', 'bob@example.com')");
        $this->behind->exec("INSERT INTO posts (user_id, title, status) VALUES (1, 'First', 'active'), (1, 'Second', 'draft'), (2, 'Bob', 'active')");
        $db = $this->database(['cache' => ['tables' => ['users', 'posts', 'counters'], 'queries' => ['posts' => ['user_id', 'status']], 'ttl' => 60]], true);

        self::assertSame('Ann', $db->table('users')->find(1)['name'] ?? null);
        self::assertSame(['First', 'Second'], array_column($db->table('posts')->where('user_id', 1)->orderBy('id')->cache(60)->get(), 'title'));
        self::assertSame(['First', 'Bob'], array_column($db->table('posts')->where('status', 'active')->orderBy('id')->cache(60)->get(), 'title'));
        $this->behind->exec("UPDATE users SET name = 'behind'");
        $this->behind->exec("UPDATE posts SET title = 'behind'");
        self::assertSame('Ann', $db->table('users')->find(1)['name'] ?? null, 'served from the row cache');
        self::assertSame(['First', 'Second'], array_column($db->table('posts')->where('user_id', 1)->orderBy('id')->cache(60)->get(), 'title'), 'served from the query cache');

        $db->table('posts')->where('id', 3)->update(['status' => 'draft']);
        self::assertSame(['behind'], array_column($db->table('posts')->where('status', 'active')->orderBy('id')->cache(60)->get(), 'title'), 'a text tag (deterministic collation) invalidated the status query');
        self::assertSame(['First', 'Second'], array_column($db->table('posts')->where('user_id', 1)->orderBy('id')->cache(60)->get(), 'title'), "a write to Bob's post leaves Ann's query cached");

        $db->table('users')->where('id', 1)->delete(); // ON DELETE CASCADE into posts
        self::assertNull($db->table('users')->find(1));
        self::assertSame([], $db->table('posts')->where('user_id', 1)->orderBy('id')->cache(60)->get());

        self::assertSame(0, $db->table('counters')->find(1)['n'] ?? null);
        $db->table('audit')->insert(['note' => 'x']); // the PL/pgSQL trigger updates counters
        self::assertSame(1, $db->table('counters')->find(1)['n'] ?? null, 'the trigger function body is followed');
        self::assertGreaterThan(0, $db->cacheStats()['hits']);
    }

    /** @param array<string, mixed> $extra */
    private function database(array $extra = [], bool $redis = false): Database
    {
        $client = null;
        if ($redis) {
            $client = new RedisClient(RedisConfig::fromArray(['host' => Services::redisHost(), 'port' => Services::redisPort(), 'prefix' => 'pg-cache-' . uniqid() . ':']));
            $this->clients[] = $client;
        }
        $manager = new DatabaseManager(Services::pgConfig(self::DB, $extra), null, $client);
        $this->managers[] = $manager;

        return $manager->connection();
    }
}
