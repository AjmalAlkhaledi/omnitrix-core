<?php

declare(strict_types=1);

namespace Omnitrix\Tests\Unit\Database;

use Omnitrix\Database\Schema\Blueprint;
use Omnitrix\Database\Schema\PostgresSchemaGrammar;
use Omnitrix\Tests\Support\TestCase;
use PHPUnit\Framework\Attributes\CoversClass;

#[CoversClass(PostgresSchemaGrammar::class)]
final class PostgresSchemaGrammarTest extends TestCase
{
    public function testCreateTableUsesIdentityColumnsAndSeparateIndexes(): void
    {
        $table = new Blueprint('posts', creating: true);
        $table->id();
        $table->foreignId('user_id')->constrained()->cascadeOnDelete();
        $table->string('title', 200)->comment('shown in lists');
        $table->string('slug')->unique();
        $table->text('body')->nullable();
        $table->enum('status', ['draft', 'published'])->default('draft');
        $table->boolean('featured')->default(false);
        $table->decimal('price', 10, 2)->unsigned()->default(0);
        $table->json('meta')->nullable();
        $table->binary('blob')->nullable();
        $table->timestamp('published_at')->nullable()->index();
        $table->timestamps();
        $table->index(['user_id', 'status']);
        $table->fullText('body');

        self::assertSame([
            "CREATE TABLE \"posts\" (\n"
            . "    \"id\" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,\n"
            . "    \"user_id\" BIGINT NOT NULL,\n"
            . "    \"title\" VARCHAR(200) NOT NULL,\n"
            . "    \"slug\" VARCHAR(255) NOT NULL,\n"
            . "    \"body\" TEXT NULL,\n"
            . "    \"status\" VARCHAR(255) DEFAULT 'draft' NOT NULL CHECK (\"status\" IN ('draft', 'published')),\n"
            . "    \"featured\" BOOLEAN DEFAULT FALSE NOT NULL,\n"
            . "    \"price\" DECIMAL(10, 2) DEFAULT 0 NOT NULL,\n"
            . "    \"meta\" JSONB NULL,\n"
            . "    \"blob\" BYTEA NULL,\n"
            . "    \"published_at\" TIMESTAMP(0) NULL,\n"
            . "    \"created_at\" TIMESTAMP(0) NULL,\n"
            . "    \"updated_at\" TIMESTAMP(0) NULL,\n"
            . "    CONSTRAINT \"posts_user_id_foreign\" FOREIGN KEY (\"user_id\") REFERENCES \"users\" (\"id\") ON DELETE CASCADE ON UPDATE RESTRICT\n"
            . ')',
            'CREATE UNIQUE INDEX "posts_slug_unique" ON "posts" ("slug")',
            'CREATE INDEX "posts_published_at_index" ON "posts" ("published_at")',
            'CREATE INDEX "posts_user_id_status_index" ON "posts" ("user_id", "status")',
            "CREATE INDEX \"posts_body_fulltext\" ON \"posts\" USING gin (to_tsvector('simple', coalesce(\"body\"::text, '')))",
            "COMMENT ON COLUMN \"posts\".\"title\" IS 'shown in lists'",
        ], (new PostgresSchemaGrammar())->compile($table));
    }

    public function testAlterRenameDropAndDropAll(): void
    {
        $table = new Blueprint('posts', creating: false);
        $table->string('subtitle')->nullable()->after('title');
        $table->renameColumn('body', 'content');
        $table->dropColumn('legacy');
        $table->dropIndex('posts_slug_unique');
        $table->dropForeign('posts_user_id_foreign');
        $table->unique('subtitle');
        $grammar = new PostgresSchemaGrammar();

        self::assertSame([
            'ALTER TABLE "posts" DROP CONSTRAINT "posts_user_id_foreign"',
            'DROP INDEX "posts_slug_unique"',
            'ALTER TABLE "posts" RENAME COLUMN "body" TO "content"',
            'ALTER TABLE "posts" ADD COLUMN "subtitle" VARCHAR(255) NULL, DROP COLUMN "legacy"',
            'CREATE UNIQUE INDEX "posts_subtitle_unique" ON "posts" ("subtitle")',
        ], $grammar->compile($table));
        self::assertSame('ALTER TABLE "a" RENAME TO "b"', $grammar->compileRename('a', 'b'));
        self::assertSame(['DROP TABLE IF EXISTS "a", "b" CASCADE'], $grammar->compileDropAll(['a', 'b']));
        self::assertSame([], $grammar->compileDropAll([]));
    }
}
